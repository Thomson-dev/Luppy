create table public.chats (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null,
  user_name text not null,
  avatar_url text not null default '',
  is_online boolean not null default false,
  updated_at timestamptz not null default now()
);

create table public.messages (
  id bigint generated by default as identity primary key,
  chat_id uuid not null references public.chats(id) on delete cascade,
  sender_id uuid not null,
  text text not null check (length(trim(text)) > 0),
  sent_at timestamptz not null default now()
);

create index messages_chat_sent_at_idx on public.messages(chat_id, sent_at);

alter table public.chats enable row level security;
alter table public.messages enable row level security;

create policy "Users can read chats" on public.chats for select to authenticated using (true);
create policy "Users can read messages" on public.messages for select to authenticated using (true);
create policy "Users can send messages" on public.messages for insert to authenticated with check (auth.uid() = sender_id);
